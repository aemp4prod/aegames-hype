#!/usr/bin/env python3
"""0.28.1: writes src/ach-icons.js, the achievements' icons (svg/ach-<key>.svg), in the order of src/succes.js.
Every achievement must have its icon (the build stops otherwise). Never edit src/ach-icons.js by hand."""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
GAME = HERE.parent.parent / 'src'
src = (GAME / 'succes.js').read_text(encoding='utf-8')
block = re.search(r'const ACH = \[(.*?)\n\];', src, re.S).group(1)
keys = re.findall(r"\{ id: '([a-z0-9-]+)', grp:", block)
assert len(keys) == len(set(keys)) and keys, 'the list of src/succes.js'
missing = [k for k in keys if not (HERE / 'svg' / ('ach-' + k + '.svg')).exists()]
assert not missing, 'no icon for: ' + ', '.join(missing)
rows = []
for k in keys:
    svg = (HERE / 'svg' / ('ach-' + k + '.svg')).read_text(encoding='utf-8').strip().replace('\n', '')
    assert '`' not in svg and '${' not in svg, k
    rows.append((k, svg))
head = ('/* =========================================================\n'
        '   0.28.1: the achievements\' icons, one original sticker each, style « Autocollant » (generated by\n'
        '   tools/emoji/make_ach.py from tools/emoji/svg/ach-*.svg: do not edit by hand). Key → svg.\n'
        '   ========================================================= */\n')
body = 'const ACH_ICONS = {\n' + ',\n'.join('  %s: `%s`' % (json.dumps(k), svg) for k, svg in rows) + ',\n};\n'
(GAME / 'ach-icons.js').write_text(head + body, encoding='utf-8')
print('ach-icons.js', len(head + body), 'bytes;', len(rows), 'icons')
